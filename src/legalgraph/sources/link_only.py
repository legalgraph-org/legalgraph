"""Link-only references: someone else's writing (news, law-firm summaries, enforcement databases) is
not kept in sources/. sources/link-only.yaml lists the page, why it is only linked, the claim it backs
up and at most one short verbatim excerpt; `extract` turns it into lgo:ExternalReference resources."""

import datetime as dt
from pathlib import Path

import yaml
from pydantic import BaseModel, ConfigDict, Field, ValidationError, field_validator
from rdflib import DCTERMS, RDF, RDFS, XSD, Graph, Literal

from legalgraph import LG, LGO
from legalgraph.sources.constants import EXCERPT_LIMIT, LINK_ONLY
from legalgraph.sources.model import SourceError, repo_path, validation_message
from legalgraph.sources.text import collapse
from legalgraph.turtle import serialize


class Excerpt(BaseModel):
    model_config = ConfigDict(extra="forbid")

    text: str
    locator: str
    language: str

    @field_validator("text", mode="before")
    @classmethod
    def short(cls, value: object) -> str:
        text = collapse(str(value))
        if len(text) > EXCERPT_LIMIT:
            raise ValueError(
                f"the quote has {len(text)} characters; someone else's work is quoted"
                f" in at most {EXCERPT_LIMIT} (one or two sentences), or linked"
            )
        return text

    @field_validator("text", "locator", "language", mode="after")
    @classmethod
    def given(cls, value: str) -> str:
        if not value:
            raise ValueError("a quote needs text, locator and language")
        return value

    @field_validator("locator", mode="before")
    @classmethod
    def as_text(cls, value: object) -> str:
        return str(value)


class LinkOnly(BaseModel):
    """One entry of sources/link-only.yaml."""

    model_config = ConfigDict(extra="forbid")

    id: str = Field(pattern=r"^[a-z0-9][a-z0-9-]*$")
    title: str
    publisher: str
    url: str
    date: dt.date | None = None
    why_link_only: str
    claim: str | None = None
    supports: list[str] = Field(default_factory=list)
    quote: Excerpt | None = None

    def add_to(self, graph: Graph) -> None:
        node = LG[f"ref-{self.id}"]
        graph.add((node, RDF.type, LGO.ExternalReference))
        graph.add((node, DCTERMS.title, Literal(self.title)))
        graph.add((node, DCTERMS.publisher, Literal(self.publisher)))
        graph.add((node, LGO.sourceUrl, Literal(self.url, datatype=XSD.anyURI)))
        graph.add((node, LGO.linkOnlyReason, Literal(self.why_link_only)))
        if self.date:
            graph.add((node, DCTERMS.date, Literal(self.date.isoformat(), datatype=XSD.date)))
        if self.claim:
            graph.add((node, RDFS.comment, Literal(self.claim, lang="en")))
        for target in self.supports:
            graph.add((node, LGO.supports, LG[target]))
        if self.quote:
            graph.add((node, LGO.excerpt, Literal(self.quote.text, lang=self.quote.language)))
            graph.add((node, LGO.excerptLocator, Literal(self.quote.locator)))


def parse_entries(path: Path) -> list[LinkOnly]:
    where = repo_path(path)
    entries, seen = [], set()
    for number, entry in enumerate(yaml.safe_load(path.read_text()) or [], 1):
        try:
            reference = LinkOnly.model_validate(entry)
        except ValidationError as error:
            raise SourceError(f"{where}: entry {number}: {validation_message(error)}") from error
        if reference.id in seen:
            raise SourceError(f"{where}: id {reference.id!r} appears twice")
        seen.add(reference.id)
        entries.append(reference)
    return entries


def extract_link_only(path: Path = LINK_ONLY) -> str | None:
    """Turtle for sources/link-only.yaml, or None when there is no such file."""
    if not path.exists():
        return None
    graph = Graph()
    for reference in parse_entries(path):
        reference.add_to(graph)
    comment = (
        f"Generated by `legalgraph sources extract` from {repo_path(path)}. Do not edit:\n"
        "change the list and run the command again."
    )
    return serialize(graph, comment)
